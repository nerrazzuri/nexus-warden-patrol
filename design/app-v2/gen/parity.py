def make():
    n = sum(len(r) for _, r in R)
    cnt = {k: sum(1 for _, r in R for x in r if x[2] == k) for k in ('已画', '部分', '没画')}
    rows = ''
    for g, items in R:
        rows += f'<tr><td colspan="3" style="padding:16px 12px 6px;font-weight:700;font-size:15px;border-bottom:1px solid {L["rule"]}">{g}</td></tr>'
        for a, b, c in items:
            sign = {'已画': '<span class="sq"></span>', '部分': '<span class="tri"></span>', '没画': '<span class="p3"></span>'}[c]
            rows += f'<tr><td style="padding:9px 12px;border-bottom:1px solid {L["rule"]}">{a}</td><td style="padding:9px 12px;border-bottom:1px solid {L["rule"]}">{b}</td><td style="padding:9px 12px;border-bottom:1px solid {L["rule"]};white-space:nowrap"><span style="display:inline-flex;align-items:center;gap:8px">{sign}{c}</span></td></tr>'
    body = f'''<div style="padding:28px 32px;flex:1">
  <h1 class="h1" style="font-size:26px;line-height:32px">老 App 功能 → 新稿对照</h1>
  <p class="mut" style="margin:6px 0 18px">共 {n} 项：已画 {cnt['已画']} · 部分 {cnt['部分']} · 没画 {cnt['没画']}。「部分」和「没画」的照老功能做，排版沿用同一套。</p>
  <table style="width:100%;border-collapse:collapse;font-size:14px;line-height:20px;background:#fff;border:1px solid {L['rule']}">
  <thead><tr><th style="text-align:left;padding:10px 12px;font-size:12px;letter-spacing:.06em;color:{L['mut']};border-bottom:1px solid {L['rule']};width:38%">老 App 功能</th><th style="text-align:left;padding:10px 12px;font-size:12px;letter-spacing:.06em;color:{L['mut']};border-bottom:1px solid {L['rule']}">新稿里在哪</th><th style="text-align:left;padding:10px 12px;font-size:12px;letter-spacing:.06em;color:{L['mut']};border-bottom:1px solid {L['rule']};width:90px">状态</th></tr></thead>
  <tbody>{rows}</tbody></table></div>'''
    h = 200 + n * 39 + len(R) * 44
    return board('App-parity', 'App · 老功能对照', body, light=True, w=1100, h=h)


